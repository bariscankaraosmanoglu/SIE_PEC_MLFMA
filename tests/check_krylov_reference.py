#!/usr/bin/env python3
"""Full-solver status checks with the CFIE driver's independent operator residual."""
import argparse
import math
import os
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solver", type=Path, required=True)
    parser.add_argument("--operator-driver", type=Path, required=True, help="cfie_operators built by check_cfie.py")
    parser.add_argument("--reference-input", type=Path, required=True, help="reference/input.pnu generated by check_cfie.py")
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    output = (args.output_dir or Path(tempfile.mkdtemp(prefix="mlfma-krylov-reference-"))).resolve()
    output.mkdir(parents=True, exist_ok=True)
    solver, verifier = args.solver.resolve(), args.operator_driver.resolve()
    base = args.reference_input.read_text().replace("source_PW 37 37 1 19 19 1 0", "source_PW 37 37 1 19 19 1 1")
    env = dict(os.environ, OMP_DYNAMIC="FALSE", ASAN_OPTIONS="detect_leaks=0", UBSAN_OPTIONS="halt_on_error=1")
    cases = [(f"pc{pc}", pc, 192, 15, 1, "converged", 0) for pc in (0, 1, 2)]
    cases += [(f"multiple-pc{pc}", pc, 192, 15, 2, "converged", 0) for pc in (0, 1, 2)]
    cases += [("limited-pc0", 0, 1, 15, 1, "iteration_limit", 1),
              ("limited-pc2", 2, 1, 15, 1, "iteration_limit", 1),
              ("limited-inner", 2, 192, 1, 1, "converged", 0),
              ("invalid-inner", 2, 192, -1, 1, "input_error", 1)]
    for name, pc, maxit, inner, illuminations, expected_status, expected_exit in cases:
        directory = output / name; directory.mkdir(exist_ok=True)
        text = base.replace("Preconditioners 2", f"Preconditioners {pc}").replace(
            "val_itermax 192", f"val_itermax {maxit}").replace("val_itermax_pc 15", f"val_itermax_pc {inner}")
        if illuminations == 2:
            text = text.replace("source_PW 37 37 1 19 19 1 1", "source_PW 37 37 1 19 19 2 1")
        (directory / "input.pnu").write_text(text)
        with (directory / "run.log").open("w") as log:
            result = subprocess.run(["/usr/bin/time", "-f", "elapsed=%e peak_rss_kib=%M", "-o", "resources.txt", str(solver)],
                                    cwd=directory, env=env, stdout=log, stderr=log, timeout=30)
        assert result.returncode == expected_exit, (name, result.returncode, directory / "run.log")
        if expected_status == "input_error":
            log = (directory / "run.log").read_text()
            assert "Input error" in log and "val_itermax_pc" in log
            assert not (directory / "result_solver_status.txt").exists()
            assert not (directory / "result_rwgcoefficient.txt").exists()
            print(name, "rejected before assembly", flush=True)
            continue
        rows = [line.split() for line in (directory / "result_solver_status.txt").read_text().splitlines() if not line.startswith("#")]
        assert len(rows) == illuminations
        for index, row in enumerate(rows):
            assert int(row[0]) == index and row[1] == expected_status, (name, row)
            assert int(row[3]) <= maxit
            assert math.isfinite(float(row[6]))
            if expected_status == "converged":
                assert float(row[5]) <= float(row[7]) and float(row[6]) <= float(row[7])
                if index == 1: assert int(row[3]) == 0, (name, row)
        # Approximate fields/coefficients are retained on failure and explicitly
        # labeled by result_solver_status.txt; they must remain finite.
        coefficients = [float(value) for value in (directory / "result_rwgcoefficient.txt").read_text().split()]
        assert coefficients and all(math.isfinite(value) for value in coefficients)
        checkdir = directory / "independent-check"; checkdir.mkdir(exist_ok=True)
        (checkdir / "input.pnu").write_text(base)
        with (checkdir / "run.log").open("w") as log:
            check = subprocess.run([str(verifier), "reference", "1", str(directory / "result_rwgcoefficient.txt")],
                                   cwd=checkdir, env=env, stdout=log, stderr=log, timeout=30)
        assert check.returncode == int(expected_exit != 0), (name, checkdir / "run.log")
        line = next(line for line in (checkdir / "run.log").read_text().splitlines() if line.startswith("CHECK independent_residual"))
        independent = float(line.split()[2]); reported = float(rows[-1][6])
        assert abs(independent-reported) <= 1e-8*max(1.0, independent), (name, independent, reported)
        print(name, "status=" + expected_status, "physical_residual=" + str(reported),
              (directory / "resources.txt").read_text().strip(), flush=True)
    print("Artifacts:", output)


if __name__ == "__main__":
    main()
